const decode = (bytes: Uint8Array) => new TextDecoder().decode(bytes);

type Files = Record<string, string | null>;

async function writeFiles(repo: string, files: Files) {
  for (const [path, content] of Object.entries(files)) {
    const full = join(repo, path);
    if (content === null) {
      await Deno.remove(full);
    } else {
      await Deno.mkdir(dirname(full), { recursive: true });
      await Deno.writeTextFile(full, content);
    }
  }
}

/**
 * Commits `base`, then `change` on top, and runs the gate against the first commit.
 * `prepare` may tamper with the repository just before the gate runs.
 */
async function gate(base: Files, change: Files, prepare?: (repo: string) => Promise<void>) {
  const repo = await Deno.makeTempDir();
  const git = async (...args: string[]) => {
    const { stdout } = await new Deno.Command("git", {
      args: ["-c", "user.email=t@example.com", "-c", "user.name=t", ...args],
      cwd: repo,
      stdout: "piped",
    }).output();
    return decode(stdout).trim();
  };
  await git("init", "-q", "-b", "main");
  await writeFiles(repo, base);
  await git("add", "-A");
  await git("commit", "-q", "-m", "base");
  const baseSha = await git("rev-parse", "HEAD");
  await writeFiles(repo, change);
  await git("add", "-A");
  await git("commit", "-q", "-m", "change");
  if (prepare) await prepare(repo);
  const { code, stdout, stderr } = await new Deno.Command(Deno.execPath(), {
    args: ["run", "--allow-run=git", gatePath, baseSha],
    cwd: repo,
    stdout: "piped",
    stderr: "piped",
  }).output();
  return { code, out: decode(stdout) + decode(stderr) };
}

const CREDO = (
  entries: string[],
  checks = ["  {Jump.CredoChecks.VacuousTest, []},", "  {ExSlop.Check.Refactor.CaseTrueFalse, []}"],
) =>
  [
    "# >>> baseline (generated by credo_baseline.ts; may only shrink)",
    "baseline = %{",
    "  Credo.Check.Readability.ModuleDoc => [",
    ...entries.map((entry) => `    ${entry}`),
    "  ],",
    "}",
    "# <<< baseline",
    "",
    "guardrail_checks = [",
    ...checks,
    "]",
    "",
  ].join("\n");

const WEB = (xrefs: string[]) =>
  [
    "defmodule MyAppWeb do",
    "  use Boundary,",
    "    deps: [MyApp],",
    "    exports: [Endpoint],",
    "    # >>> baseline",
    "    dirty_xrefs: [",
    ...xrefs.map((xref) => `      ${xref}`),
    "    ]",
    "",
    "  # <<< baseline",
    "end",
    "",
  ].join("\n");

const MIX = (n: number) =>
  `defmodule App.MixProject do\n  # aliases\n  precommit: ["xref graph --label compile-connected --fail-above ${n}"]\nend\n`;

// ---- unit ----

Deno.test("parseDiff numbers removed lines in the old file and added lines in the new one", () => {
  const diff = ["diff --git a/x.exs b/x.exs", "--- a/x.exs", "+++ b/x.exs", "@@ -3,2 +3,1 @@", "-a", "-b", "+c", ""]
    .join("\n");
  assertEquals(parseDiff(diff), [{
    path: "x.exs",
    removed: [{ line: 3, text: "a" }, { line: 4, text: "b" }],
    added: [{ line: 3, text: "c" }],
  }]);
});

Deno.test("baselineRanges covers the marker lines and everything between them", () => {
  assertEquals(baselineRanges("a\n# >>> baseline\nb\n  # <<< baseline\nc\n"), [[2, 4]]);
});

